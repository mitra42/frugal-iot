def image_bytes(elf: Path) -> int:
    """Flash+RAM bytes the image actually occupies, from the ELF's own section headers.

    Deliberately measured from the ELF rather than from firmware.bin. Only the deltas matter here,
    and firmware.bin is this total plus a constant ~153-byte header - but producing the .bin needs
    esptool, the bootloader and the partition table, which is both slower and a recurring source
    of unrelated breakage. Building only the ELF
    sidesteps all of it.
    """
    return sum(size for size, nb in elf_alloc(elf).values() if not nb)


def build(env, src_dir: Path, build_dir: Path, extra_flags):
    """Run pio for one generated sketch. Returns (image bytes, error text or None)."""
    envv = dict(os.environ)
    envv["PLATFORMIO_SRC_DIR"] = str(src_dir)
    envv["PLATFORMIO_BUILD_DIR"] = str(build_dir)
    if extra_flags:
        # PlatformIO appends this to the env's build_flags rather than replacing them.
        envv["PLATFORMIO_BUILD_FLAGS"] = " ".join(extra_flags)
    elf = build_dir / env / "firmware.elf"
    if elf.exists():
        elf.unlink()                       # never report a stale ELF as this module's result
    r = subprocess.run(["pio", "run", "-e", env, "-t", str(elf)], cwd=PROJECT, env=envv,
                       capture_output=True, text=True)
    # Judge success on the ELF existing, not on the exit code. Asking for the ELF target still
    # drags bootloader.bin along, and that step needs esptool - which breaks periodically on this
    # machine for reasons that have nothing to do with the sketch (see the esptool notes). The ELF
    # is linked before that fails, so if it is there the measurement is good.
    if not elf.exists():
        errs = [l for l in (r.stdout + r.stderr).splitlines()
                if re.search(r"\berror\b", l, re.I)]
        return None, "\n".join(errs[:4]) or "build failed with no recognisable error line"
    return image_bytes(elf), None


def write_sketch(dirpath: Path, body="", globals_="") -> Path:
    dirpath.mkdir(parents=True, exist_ok=True)
    (dirpath / "main.cpp").write_text(SKELETON % {"body": body, "globals": globals_})
    return dirpath


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-e", "--env", default="c3_pico")
    ap.add_argument("--only", nargs="*", help="just these modules")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--markdown", action="store_true")
    ap.add_argument("--keep", action="store_true", help="leave the scratch tree for inspection")
    args = ap.parse_args()

    if args.list:
        for k in sorted(MODULES):
            print(k)
        return

    wanted = args.only or sorted(MODULES)
    unknown = [m for m in wanted if m not in MODULES]
    if unknown:
        sys.exit(f"unknown module(s): {', '.join(unknown)}\nsee --list")

    build_dir = SCRATCH / "build"
    src_root = SCRATCH / "src"
    print(f"env: {args.env}   scratch: {SCRATCH}")
    print("(first build is slow; the rest reuse the object tree)\n")

    print(f"{'baseline':<20}", end="", flush=True)
    base, err = build(args.env, write_sketch(src_root / "_baseline"), build_dir, [])
    if base is None:
        sys.exit(f"\nbaseline build failed:\n{err}")
    print(f"{base:>12,} bytes")

    results = []
    for name in wanted:
        body, flags, globs = MODULES[name]
        print(f"{name:<20}", end="", flush=True)
        size, err = build(args.env, write_sketch(src_root / name, body, globs), build_dir, flags)
        if size is None:
            print("  FAILED")
            results.append((None, name, err))
        else:
            print(f"{size:>12,}   {size - base:>+9,}")
            results.append((size - base, name, None))

    ok = sorted((r for r in results if r[0] is not None), reverse=True)
    bad = [r for r in results if r[0] is None]

    print(f"\n{'=' * 62}\nCost of each module on {args.env}, over a {base:,} byte baseline\n"
          f"{'=' * 62}")
    if args.markdown:
        print(f"\n| module | image bytes | cost |\n|---|---|---|")
        print(f"| *(baseline)* | {base:,} | — |")
        for delta, name, _ in ok:
            print(f"| `{name}` | {base + delta:,} | {delta:+,} |")
    else:
        for delta, name, _ in ok:
            print(f"  {name:<20}{delta:>+10,}")
    for _d, name, err in bad:
        print(f"  {name:<20}   did not build: {err.splitlines()[0][:80] if err else '?'}")

    if not args.keep:
        shutil.rmtree(SCRATCH, ignore_errors=True)
    else:
        print(f"\nscratch kept at {SCRATCH}")


if __name__ == "__main__":
    main()
