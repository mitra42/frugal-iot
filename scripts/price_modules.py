#!/usr/bin/env python3
"""
Price each optional module in flash bytes.

Builds a minimal sketch, then rebuilds it once per module with just that one module added, and
reports the difference in image size. The point is to find modules that drag in far more than
they look like they should - the way LoRaMesher's std::ostringstream turned out to be worth
230,464 bytes of C++ locale machinery. That was invisible until measured, so this measures
everything rather than guessing which to suspect.

It never touches src/main.cpp. Generated sketches go in a scratch directory and PLATFORMIO_SRC_DIR
points the build at them; PLATFORMIO_BUILD_DIR keeps the object files out of your real .pio/build
so your normal builds are not disturbed or invalidated. The scratch build dir is reused between
modules on purpose - only main.cpp and the newly-reached library objects recompile, so after the
first build each module costs seconds rather than minutes.

Usage:
    lib/Frugal-IoT/scripts/price_modules.py                        # every module, on c3_pico
    lib/Frugal-IoT/scripts/price_modules.py -e ttgo-lora32-v21
    lib/Frugal-IoT/scripts/price_modules.py --only ds18b20 loadcell
    lib/Frugal-IoT/scripts/price_modules.py --list
    lib/Frugal-IoT/scripts/price_modules.py --markdown             # table ready to paste into the results file
"""

